/// One run of scalars a command refers to in the coordinate arena.
///
/// Mirrors `kgds_coord_ref`, except that `count` is widened to `u64`. The C
/// function computes a point run's length as `2u * arg1` in `uint32_t`, which
/// wraps for `arg1 >= 2^31`; widening here means a wrapped length shows up as a
/// range error instead of silently naming the wrong bytes.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct CoordRef {
    /// Index of the first scalar.
    pub start: u32,
    /// Number of scalars.
    pub count: u64,
}

/// The `kgds_coord_ref` record exactly as C lays it out, for the rare caller
/// that needs to exchange one across the boundary. Prefer [`CoordRef`].
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct kgds_coord_ref {
    pub start: u32,
    pub count: u32,
}

const _: () = assert!(size_of::<kgds_coord_ref>() == 8);

/// Upper bound on the number of coordinate runs any single command refers to.
/// Mirrors `KGDS_MAX_COORD_REFS`.
pub const MAX_COORD_REFS: usize = 3;

/// The coordinate runs a single command refers to.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct CoordRefs {
    refs: [CoordRef; MAX_COORD_REFS],
    len: usize,
}

impl CoordRefs {
    /// The runs, in the order the C function writes them.
    pub fn as_slice(&self) -> &[CoordRef] {
        &self.refs[..self.len]
    }

    fn push(&mut self, start: u32, count: u64) {
        self.refs[self.len] = CoordRef { start, count };
        self.len += 1;
    }
}

impl std::ops::Deref for CoordRefs {
    type Target = [CoordRef];
    fn deref(&self) -> &[CoordRef] {
        self.as_slice()
    }
}

/// Report which runs of the coordinate arena a command refers to.
///
/// The Rust twin of `kgds_coord_refs`, which the header calls the single source
/// of truth for this mapping: the producer relocates live geometry with it when
/// it compacts an arena, and this crate bounds-checks a stream with it. The two
/// must agree exactly, and `tests/header_sync.rs` parses the C function and
/// compares it against this one to make sure they do.
///
/// Commands that carry no coordinates — state changes, group references, frame
/// markers — return no runs. So does an unrecognised opcode, matching the C
/// `default` arm; callers must reject unknown opcodes separately rather than
/// reading an empty result as "nothing to check".
pub fn coord_refs(cmd: &kgds_cmd) -> CoordRefs {
    let mut out = CoordRefs::default();
    let Some(op) = Op::from_raw(cmd.op) else {
        return out;
    };

    // A point run holds two scalars per point; computed in u64 so that a
    // hostile count fails a range check rather than wrapping into a small one.
    let run = |n: u32| -> u64 { 2 * (n as u64) };

    match op {
        Op::SetLineWidth | Op::SetMinLineWidth | Op::SetLayerDepth | Op::Rotate => {
            out.push(cmd.arg0, 1)
        }
        Op::Translate | Op::Scale | Op::Cursor => out.push(cmd.arg0, 2),
        Op::Transform | Op::Grid => out.push(cmd.arg0, 6),
        Op::Line | Op::Rectangle => out.push(cmd.arg0, 4),
        Op::Segment => {
            out.push(cmd.arg0, 4);
            out.push(cmd.arg1, 1);
        }
        Op::SegmentChain => {
            out.push(cmd.arg0, run(cmd.arg1));
            out.push(cmd.arg2, 1);
        }
        Op::Polyline | Op::Polygon => out.push(cmd.arg0, run(cmd.arg1)),
        Op::Circle => out.push(cmd.arg0, 3),
        Op::HoleWall => {
            out.push(cmd.arg0, 3);
            out.push(cmd.arg1, 1);
        }
        Op::Arc => out.push(cmd.arg0, 5),
        Op::ArcSegment => {
            out.push(cmd.arg0, 5);
            out.push(cmd.arg1, 1);
        }
        Op::Curve => out.push(cmd.arg0, 8),
        Op::Ellipse => {
            out.push(cmd.arg0, 4);
            out.push(cmd.arg1, 1);
        }
        Op::EllipseArc => {
            out.push(cmd.arg0, 4);
            out.push(cmd.arg1, 3);
            out.push(cmd.arg2, 1);
        }
        Op::Bitmap => {
            // arg0 is an image table index, not a coordinate.
            out.push(cmd.arg1, 6);
            out.push(cmd.arg2, 1);
        }
        Op::DrawGroup => {
            // arg0 is a group id, not a coordinate. Only the optional depth
            // override refers to the arena.
            if cmd.flags & flags::GROUP_DEPTH != 0 {
                out.push(cmd.arg2, 1);
            }
        }
        Op::Nop
        | Op::BeginFrame
        | Op::EndFrame
        | Op::ClearScreen
        | Op::SetTarget
        | Op::ClearTarget
        | Op::StartDiffLayer
        | Op::EndDiffLayer
        | Op::StartNegativesLayer
        | Op::EndNegativesLayer
        | Op::SetIsFill
        | Op::SetIsStroke
        | Op::SetFillColor
        | Op::SetStrokeColor
        | Op::SetHoverColor
        | Op::SetNegativeDrawMode
        | Op::EnableDepthTest
        | Op::Save
        | Op::Restore => {}
    }

    out
}

/// Render target. Mirrors `kgds_target`, which matches `KIGFX::RENDER_TARGET`.
#[repr(u32)]
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Default)]
pub enum Target {
    #[default]
    Cached = 0,
    NonCached = 1,
    Overlay = 2,
    Temp = 3,
}

impl Target {
    /// Convert a raw target value, returning `None` if unknown.
    pub const fn from_raw(raw: u32) -> Option<Target> {
        match raw {
            0 => Some(Target::Cached),
            1 => Some(Target::NonCached),
            2 => Some(Target::Overlay),
            3 => Some(Target::Temp),
            _ => None,
        }
    }
}

/// Pixel format of an image table entry. Mirrors `kgds_image_format`.
#[repr(u32)]
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Default)]
pub enum ImageFormat {
    #[default]
    Rgba8 = 0,
}

impl ImageFormat {
    /// Bytes per pixel for this format.
    pub const fn bytes_per_pixel(self) -> u64 {
        match self {
            ImageFormat::Rgba8 => 4,
        }
    }

    /// Convert a raw format value, returning `None` if unknown.
    pub const fn from_raw(raw: u32) -> Option<ImageFormat> {
        match raw {
            0 => Some(ImageFormat::Rgba8),
            _ => None,
        }
    }
}

