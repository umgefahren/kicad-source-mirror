//! Hand-written `#[repr(C)]` mirrors of `include/gal/recording/draw_stream_abi.h`.
//!
//! These are deliberately *not* generated by `bindgen`. The header is small,
//! stable and plain C, and hand-mirroring it keeps this crate buildable with no
//! C toolchain and no build script — which matters because the Rust renderer is
//! developed and tested long before the C++ producer exists.
//!
//! Agreement with the header is enforced two ways:
//!
//! * the `const _: () = assert!(...)` layout assertions below, which mirror the
//!   `static_assert`s in the header and fail at compile time; and
//! * [`tests/header_sync.rs`], which reads the header text at test time and
//!   checks that every opcode name and number still matches [`Op`].

// These are raw mirrors: the C header is the documentation for every field, and
// duplicating it here would be one more thing to let drift.
#![allow(non_camel_case_types, missing_docs)]

/// Magic number at the head of a serialised stream: `"KGDS"`, little-endian.
///
/// Mirrors `KGDS_MAGIC`.
pub const KGDS_MAGIC: u32 = 0x5344_474B;

/// ABI version this crate implements. Mirrors `KGDS_VERSION`.
///
/// A stream carrying any other version is rejected rather than guessed at: the
/// header promises that the opcode list, command layout and section table may
/// all change together on a bump.
pub const KGDS_VERSION: u32 = 1;

/// One recorded GAL call. Mirrors `kgds_cmd`; fixed at 24 bytes.
///
/// The meaning of each `arg` slot is opcode-specific; [`crate::Command`] is the
/// resolved form and is what callers should normally use.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub struct kgds_cmd {
    /// A [`Op`] discriminant. Stored raw because an unknown opcode must be
    /// diagnosable rather than undefined.
    pub op: u16,
    /// A bitwise-or of [`flags`] values.
    pub flags: u16,
    pub arg0: u32,
    pub arg1: u32,
    pub arg2: u32,
    pub arg3: u32,
    pub arg4: u32,
}

/// A cached group body, as produced by `GAL::BeginGroup`/`EndGroup`.
///
/// Mirrors `kgds_group`; fixed at 16 bytes. `serial` changes whenever the
/// group's contents are re-recorded, and is the renderer's entire cache
/// invalidation story.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub struct kgds_group {
    /// Stable identity of the group, as referenced by `KGDS_OP_DRAW_GROUP`.
    pub id: u32,
    /// Bumped by the producer whenever the body is re-recorded.
    pub serial: u32,
    /// Index of the first command of the body in the command array.
    pub first_cmd: u32,
    pub cmd_count: u32,
}

/// An embedded bitmap. Mirrors `kgds_image`; fixed at 32 bytes.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub struct kgds_image {
    pub width: u32,
    pub height: u32,
    /// A [`ImageFormat`] discriminant.
    pub format: u32,
    pub reserved: u32,
    /// Byte offset into the image arena.
    pub data_offset: u64,
    pub data_length: u64,
}

/// A borrowed view of a complete stream. Mirrors `kgds_stream_view`.
///
/// This is the struct that crosses the FFI boundary. Every pointer is owned by
/// the producer and stays valid until the next recording pass.
///
/// Retained group geometry and the current frame live in *separate* command
/// arrays and coordinate arenas, and that separation is load-bearing rather
/// than cosmetic: `KIGFX::VIEW` records an item into a group during its update
/// pass and replays it during its draw pass, so the two interleave in time. A
/// command's coordinate indices therefore refer to the arena that command lives
/// in — group bodies index `group_coords`, frame commands index `frame_coords`.
///
/// Its size is asserted to match the C side (136 bytes on a 64-bit target); the
/// assertion is skipped where `size_t` is not 64-bit, since the header's own
/// size is pointer-width dependent.
#[repr(C)]
#[derive(Clone, Copy, Debug)]
pub struct kgds_stream_view {
    /// `KGDS_VERSION` the producer was built against.
    pub version: u32,
    pub flags: u32,

    /// Retained geometry, one body per cached item. Indices use `group_coords`.
    pub group_cmds: *const kgds_cmd,
    pub group_cmd_count: usize,

    pub group_coords: *const f64,
    pub group_coord_count: usize,

    /// The group table. Each entry's `first_cmd` indexes `group_cmds`.
    pub groups: *const kgds_group,
    pub group_count: usize,

    /// This frame's command list. Indices use `frame_coords`.
    pub frame_cmds: *const kgds_cmd,
    pub frame_cmd_count: usize,

    pub frame_coords: *const f64,
    pub frame_coord_count: usize,

    pub strings: *const u8,
    pub string_bytes: usize,

    pub images: *const kgds_image,
    pub image_count: usize,

    pub image_data: *const u8,
    pub image_bytes: usize,
}

/// Header of a stream serialised to disk. Mirrors `kgds_file_header`; fixed at
/// 80 bytes. Sections follow in declaration order, each aligned to 8 bytes.
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct kgds_file_header {
    pub magic: u32,
    pub version: u32,
    pub flags: u32,
    pub reserved: u32,

    pub group_cmd_count: u64,
    pub group_coord_count: u64,
    pub group_count: u64,
    pub frame_cmd_count: u64,
    pub frame_coord_count: u64,
    pub string_bytes: u64,
    pub image_count: u64,
    pub image_bytes: u64,
}

// Layout agreement is load-bearing across the FFI boundary, so assert it here
// rather than discovering a mismatch as corrupt geometry at runtime. These
// mirror the static_asserts at the foot of the C header.
const _: () = assert!(size_of::<kgds_cmd>() == 24, "kgds_cmd must stay 24 bytes");
const _: () = assert!(size_of::<kgds_group>() == 16, "kgds_group must stay 16 bytes");
const _: () = assert!(size_of::<kgds_image>() == 32, "kgds_image must stay 32 bytes");
const _: () = assert!(
    size_of::<kgds_file_header>() == 80,
    "kgds_file_header must stay 80 bytes"
);

// The C header has no static_assert for the view, because its size depends on
// size_t. Assert it for the 64-bit case we actually ship.
const _: () = assert!(
    size_of::<usize>() != 8 || size_of::<kgds_stream_view>() == 136,
    "kgds_stream_view must stay 136 bytes on 64-bit targets"
);

// Field alignment, which a reordering would silently break even while the total
// size stayed put.
const _: () = assert!(align_of::<kgds_cmd>() == 4);
const _: () = assert!(align_of::<kgds_group>() == 4);
const _: () = assert!(align_of::<kgds_image>() == 8);
const _: () = assert!(align_of::<kgds_file_header>() == 8);

/// Bit flags in [`kgds_cmd::flags`]. Mirrors `enum kgds_flag`.
pub mod flags {
    /// The contour is a hole rather than an outline.
    pub const HOLE: u16 = 1 << 0;
    /// The point run forms a closed loop.
    pub const CLOSED: u16 = 1 << 1;
    /// The geometry came from a glyph. Ordinary geometry; needs no font
    /// support, but the renderer may batch it differently.
    pub const GLYPH: u16 = 1 << 2;

    /// On `DRAW_GROUP`: `arg1` is a packed RGBA8 colour that replaces every
    /// stroke and fill colour inside the group, for this replay only.
    ///
    /// `KIGFX::VIEW` recolours a cached item in place for selection and
    /// highlighting rather than re-recording it, so the override rides on the
    /// replay. That is deliberate and it is what keeps a renderer's
    /// `(id, serial)` cache valid across a selection change — the single most
    /// frequent thing a user does.
    pub const GROUP_COLOR: u16 = 1 << 3;

    /// On `DRAW_GROUP`: `arg2` is a coordinate index to one scalar, the depth
    /// at which to replay the group. Set for the same reason as
    /// [`GROUP_COLOR`].
    pub const GROUP_DEPTH: u16 = 1 << 4;

    /// Every bit this ABI version defines. Unknown bits are rejected so that a
    /// future producer cannot silently lose meaning against an old renderer.
    pub const KNOWN: u16 = HOLE | CLOSED | GLYPH | GROUP_COLOR | GROUP_DEPTH;
}

macro_rules! opcodes {
    ($( $(#[$m:meta])* $name:ident = $value:expr, $c:literal; )*) => {
        /// Draw stream opcodes. Mirrors `enum kgds_op`.
        ///
        /// Numbering is grouped and stable: append within a group, never
        /// renumber. The C spelling of each variant is available via
        /// [`Op::c_name`], which is what `tests/header_sync.rs` compares
        /// against the header text.
        #[repr(u16)]
        #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
        pub enum Op {
            $( $(#[$m])* $name = $value, )*
        }

        impl Op {
            /// Every opcode this ABI version defines, in numeric order.
            pub const ALL: &'static [Op] = &[ $( Op::$name, )* ];

            /// The identifier this opcode has in the C header.
            pub const fn c_name(self) -> &'static str {
                match self { $( Op::$name => $c, )* }
            }

            /// Convert a raw opcode value, returning `None` if it is not one
            /// this ABI version knows.
            ///
            /// Unknown opcodes are never skipped silently: a stream containing
            /// one is rejected, because a command whose argument meaning is
            /// unknown cannot be stepped over safely either.
            pub const fn from_raw(raw: u16) -> Option<Op> {
                match raw {
                    $( $value => Some(Op::$name), )*
                    _ => None,
                }
            }
        }
    };
}

